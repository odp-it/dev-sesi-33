-- Jangan diedit di sini: file ini disalin ulang otomatis kalau DDL sesi 22 berubah.


CREATE TABLE branches (
  branch_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  branch_code  VARCHAR2(20)  NOT NULL,
  branch_name  VARCHAR2(100) NOT NULL,
  city         VARCHAR2(50)  NOT NULL,
  CONSTRAINT pk_branches PRIMARY KEY (branch_id),
  CONSTRAINT uq_branches_code UNIQUE (branch_code)
);

CREATE TABLE customers (
  customer_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  cif_no       VARCHAR2(20)  NOT NULL,
  full_name    VARCHAR2(100) NOT NULL,
  email        VARCHAR2(100) NOT NULL,
  phone        VARCHAR2(20),
  segment      VARCHAR2(10)  NOT NULL,
  branch_id    NUMBER        NOT NULL,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_customers PRIMARY KEY (customer_id),
  CONSTRAINT uq_customers_cif UNIQUE (cif_no),
  CONSTRAINT uq_customers_email UNIQUE (email),
  CONSTRAINT fk_customers_branch FOREIGN KEY (branch_id) REFERENCES branches (branch_id)
);

-- Constraint segment ditambahkan lewat ALTER TABLE (langkah A3)
ALTER TABLE customers ADD CONSTRAINT ck_customers_segment
  CHECK (segment IN ('INDIVIDU', 'UMKM'));

CREATE TABLE accounts (
  account_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  account_no   VARCHAR2(20)  NOT NULL,
  customer_id  NUMBER        NOT NULL,
  product      VARCHAR2(10)  NOT NULL,
  balance      NUMBER(15,2)  DEFAULT 0 NOT NULL,
  status       VARCHAR2(10)  DEFAULT 'AKTIF' NOT NULL,
  opened_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_accounts PRIMARY KEY (account_id),
  CONSTRAINT uq_accounts_no UNIQUE (account_no),
  CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT ck_accounts_product CHECK (product IN ('TABUNGAN', 'GIRO')),
  CONSTRAINT ck_accounts_balance CHECK (balance >= 0),
  CONSTRAINT ck_accounts_status CHECK (status IN ('AKTIF', 'DIBLOKIR', 'DITUTUP'))
);

CREATE TABLE transactions (
  txn_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  account_id   NUMBER        NOT NULL,
  txn_type     VARCHAR2(20)  NOT NULL,
  category     VARCHAR2(20)  NOT NULL,
  amount       NUMBER(15,2)  NOT NULL,
  txn_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  description  VARCHAR2(200),
  ref_no       VARCHAR2(20)  NOT NULL,
  CONSTRAINT pk_transactions PRIMARY KEY (txn_id),
  CONSTRAINT uq_transactions_ref UNIQUE (ref_no),
  CONSTRAINT fk_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (account_id),
  CONSTRAINT ck_transactions_type CHECK (txn_type IN ('SETOR', 'TARIK', 'TRANSFER_MASUK', 'TRANSFER_KELUAR')),
  CONSTRAINT ck_transactions_category CHECK (category IN ('PENJUALAN', 'BAHAN_BAKU', 'OPERASIONAL', 'GAJI', 'TRANSFER', 'LAINNYA')),
  CONSTRAINT ck_transactions_amount CHECK (amount > 0)
);

